/**
 * Devuelve la configuración del tema solicitado o el verde original por defecto.
 */
export function getHeaderThemeConfig(themeKey) {
  if (themeKey && Object.prototype.hasOwnProperty.call(HEADER_THEMES, themeKey)) {
    return HEADER_THEMES[themeKey];
  }
  return HEADER_THEMES[DEFAULT_HEADER_THEME_KEY];
}

/**
 * Devuelve los tokens coordinados de quickActions para una acción específica.
 */
export function getQuickActionTokens(theme, actionKey) {
  const activeTheme = theme || HEADER_THEMES[DEFAULT_HEADER_THEME_KEY];
  if (activeTheme?.quickActions && activeTheme.quickActions[actionKey]) {
    return activeTheme.quickActions[actionKey];
  }
  return null;
}
