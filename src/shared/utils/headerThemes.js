/**
 * Normaliza cadenas de identidad (username / email):
 * minúsculas, sin acentos y sin prefijos numéricos tipo "001. ".
 */
function normalizeIdentityValue(value) {
  if (!value || typeof value !== "string") return "";
  return value
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/^\d+\.\s*/, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Valida estrictamente si el usuario corresponde a Misael Cumapa.
 * Replica exactamente la lógica del backend (username y email evaluados por separado,
 * sin concatenar ambos campos ni otorgar acceso por rol ADMIN).
 */
export function isMisaelCumapaUser(user) {
  if (!user || typeof user !== "object") return false;

  const normalizedUsername = normalizeIdentityValue(user.username);
  if (
    normalizedUsername &&
    normalizedUsername.includes("misael") &&
    normalizedUsername.includes("cumapa")
  ) {
    return true;
  }

  const normalizedEmail = normalizeIdentityValue(user.email);
  if (normalizedEmail) {
    const localPart = normalizedEmail.split("@")[0] || "";
    const hasFullNameInEmail =
      localPart.includes("misael") && localPart.includes("cumapa");
    const hasInitialLastNameInEmail =
      localPart === "mcumapa" || /^m[._-]?cumapa(\d+)?$/.test(localPart);

    if (hasFullNameInEmail || hasInitialLastNameInEmail) {
      return true;
    }
  }

  return false;
}

